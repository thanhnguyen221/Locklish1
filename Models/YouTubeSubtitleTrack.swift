import Foundation

// MARK: - SubtitleWord
/// One word inside a cue with YouTube's own spoken timing (absolute seconds).
public struct SubtitleWord: Codable, Equatable {
    public let text: String
    public let startTime: Double
    public let endTime: Double

    public init(text: String, startTime: Double, endTime: Double) {
        self.text = text
        self.startTime = startTime
        self.endTime = endTime
    }
}

// MARK: - SubtitleCue
public struct SubtitleCue: Identifiable, Codable, Equatable {
    public var id: String { "\(Int(startTime * 1000))_\(Int(duration * 1000))" }
    public let startTime: Double   // In seconds, e.g. 1.25
    public let duration: Double    // In seconds, e.g. 2.40
    public var endTime: Double { startTime + duration }
    public var textEn: String
    public var textVi: String
    /// Word-level spoken timings from YouTube's timedtext when available
    /// (empty when the track doesn't provide them — callers fall back to
    /// character-proportional estimates).
    public var words: [SubtitleWord]

    public init(startTime: Double, duration: Double, textEn: String, textVi: String = "", words: [SubtitleWord] = []) {
        self.startTime = startTime
        self.duration = duration
        self.textEn = textEn
        self.textVi = textVi
        self.words = words
    }

    public var formattedTimestamp: String {
        let totalSeconds = Int(startTime)
        let hours = totalSeconds / 3600
        let minutes = (totalSeconds % 3600) / 60
        let seconds = totalSeconds % 60
        if hours > 0 {
            return String(format: "%d:%02d:%02d", hours, minutes, seconds)
        } else {
            return String(format: "%02d:%02d", minutes, seconds)
        }
    }
}

// MARK: - YouTubeCaptionTrackInfo
public struct YouTubeCaptionTrackInfo: Identifiable, Codable {
    public var id: String { "\(languageCode)_\(name)" }
    public let baseUrl: String
    public let name: String
    public let languageCode: String
    public let isTranslatable: Bool
    /// "asr" when YouTube auto-generated the captions; nil for human-made tracks,
    /// which have far better wording and timing accuracy.
    public var kind: String?

    public var isAutoGenerated: Bool { kind == "asr" }

    public init(
        baseUrl: String,
        name: String,
        languageCode: String,
        isTranslatable: Bool,
        kind: String? = nil
    ) {
        self.baseUrl = baseUrl
        self.name = name
        self.languageCode = languageCode
        self.isTranslatable = isTranslatable
        self.kind = kind
    }
}

// MARK: - YouTubeVideoInfo
public struct YouTubeVideoInfo: Identifiable, Codable {
    public var id: String { videoId }
    public let videoId: String
    public let title: String
    public let author: String
    public let cues: [SubtitleCue]
    public let availableTracks: [YouTubeCaptionTrackInfo]

    public init(
        videoId: String,
        title: String,
        author: String,
        cues: [SubtitleCue],
        availableTracks: [YouTubeCaptionTrackInfo] = []
    ) {
        self.videoId = videoId
        self.title = title
        self.author = author
        self.cues = cues
        self.availableTracks = availableTracks
    }
}
